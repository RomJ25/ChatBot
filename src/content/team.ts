/*
 * ============================================================
 *  צוות שניר — תוכן קאנוני (המקור האמיתי)
 * ============================================================
 *
 *  הקובץ הזה הוא המקור היחיד לאמת על הצוות:
 *  חברים, מפקד/ת, פרויקטים, טון הדיבור.
 *
 *  איך לערוך:
 *    • כדי להוסיף חבר/ת צוות — הוסף שורה לרשימת `members`.
 *    • כדי להוסיף פרויקט — הוסף שורה לרשימת `projects`.
 *    • כדי להסיר — פשוט מחק את השורה.
 *    • שדות עם סימן שאלה (role?, description?) ניתנים להשמטה.
 *    • כל השינויים מתעדכנים אוטומטית ב-dev (Vite HMR).
 *      ל-production — הרץ `npm run build` אחרי השינוי.
 *
 *  המידע כאן מזין שני דברים:
 *    1) את ה-system prompt של ה-LLM (המודל לא ממציא דברים
 *       שלא כתובים כאן — הוא ענה רק על בסיס זה).
 *    2) את התשובות הקבועות שייכתבו בהמשך (ה-chips
 *       הקבועים יציגו את המידע הזה ללא קריאה ל-LLM).
 *
 *  לפריטי ידע חופשיים (שאלות נפוצות, מילון מושגים, תהליכים,
 *  קישורים, הערות) — ראה `src/content/knowledge.ts`.
 *  למקורות חיצוניים (Confluence וכו׳) — `src/content/sources/`.
 */

export type TeamMember = {
  name: string;
  role?: string; // לדוג׳ "מפקדת הצוות", "קב״רית"
  responsibility: string;
};

export type Project = {
  name: string;
  description?: string;
  status?: string; // פעיל, בפיתוח, הושלם — אופציונלי
  progress?: number; // 0-100, אופציונלי (לשימוש עתידי בתצוגה)
};

export type Tone = {
  voice: string;
  audience: string;
  language: string;
};

export type TeamContent = {
  name: string;
  short: string; // משפט אחד שמתאר את הצוות
  about?: string; // תיאור ארוך יותר (אופציונלי)
  commander?: TeamMember; // מפקד/ת — מוצג בנפרד אם קיים
  members: TeamMember[];
  projects: Project[];
  tone: Tone;
  welcome?: string; // הודעת פתיחה בצ'אט. אם ריק — נגזרת מ-name.
};

